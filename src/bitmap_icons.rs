//! Small bitmap icons shared by bevel buttons and document toolbars.

use crate::{Accent, paint::Pen, theme::*};

/// Paints an icon using the original Platinum bitmap palette.
pub fn draw_bitmap_icon(
    pen: &mut Pen,
    rows: &[&str],
    x: i32,
    y: i32,
    accent: Accent,
    inverted: bool,
    disabled: bool,
) {
    for (dy, row) in rows.iter().enumerate() {
        for (dx, pixel) in row.bytes().enumerate() {
            let color = match pixel {
                b'#' if inverted => WHITE,
                b'#' => BLACK,
                b'w' if inverted => BLACK,
                b'w' => WHITE,
                b'o' if inverted => accent.light,
                b'o' => accent.dark,
                b'+' => accent.mid,
                b':' => GRAY_7,
                _ => continue,
            };
            let color = if disabled { dim_color(color) } else { color };
            pen.dot(x + dx as i32, y + dy as i32, color);
        }
    }
}

fn dim_color(color: u32) -> u32 {
    let red = (color >> 16) & 255;
    let green = (color >> 8) & 255;
    let blue = color & 255;
    if red == green && green == blue {
        color.max(GRAY_8)
    } else {
        let lightness = (299 * red + 587 * green + 114 * blue) / 1000;
        let value = lightness + (255 - lightness) / 2;
        (value << 16) | (value << 8) | value
    }
}

